import { writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { demo } from '../public/canvas/demo.mjs';
import { sentences } from '../public/canvas/core.mjs';
import { prepareDocument } from '../public/canvas/document.mjs';
import { embeddings } from '../cli/engine.mjs';

const texts = [
  ...new Set([
    ...demo.turns.flatMap((turn) =>
      sentences(turn.text)
        .map((s) => s.trim())
        .filter(Boolean),
    ),
    ...demo.artifacts.flatMap((artifact) =>
      prepareDocument(artifact.text, artifact.format).units.map(
        (unit) => unit.text,
      ),
    ),
  ]),
];
const python = process.argv[2] || '.venv/bin/python';
const vectors = await embeddings(texts, { engine: 'local', python });
const model = {
  name: 'paraphrase-multilingual-MiniLM-L12-v2',
  revision: 'e8f8c211226b894fcb81acc59f3b34ba3efd5f42',
  dimensions: vectors[0].length,
  textHash: createHash('sha256').update(JSON.stringify(texts)).digest('hex'),
};
await writeFile(
  new URL('../public/canvas/demo-vectors.mjs', import.meta.url),
  `// Generated by scripts/build-canvas-demo.mjs from the edited public demo only.\nexport const demoModel = ${JSON.stringify(model)};\nexport const demoVectors = ${JSON.stringify(Object.fromEntries(texts.map((text, i) => [text, vectors[i].map((n) => Number(n.toFixed(7)))])))};\n`,
);
console.log(
  `Computed ${texts.length} demo sentences, ${model.dimensions} dimensions each.`,
);
